#!/usr/bin/env bash
# Apply ephemeral ECR + Inspector + small EKS stack; write tmp/good.txt
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TF_DIR="${ROOT}/deploy/e2e-aws"
STATE_DIR="${ROOT}/tmp/e2e-aws"
CREDS_BOOTSTRAP="${ROOT}/tmp/c.txt"
GOOD="${ROOT}/tmp/good.txt"
GOOD_ROOT="${ROOT}/good.txt"
REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:-eu-west-1}}"

need() { command -v "$1" >/dev/null || { echo "missing $1" >&2; exit 1; }; }
need terraform
need aws

if [[ ! -f "$CREDS_BOOTSTRAP" ]]; then
  echo "missing bootstrap creds: $CREDS_BOOTSTRAP" >&2
  exit 1
fi
# shellcheck disable=SC1090
source "$CREDS_BOOTSTRAP"
export AWS_DEFAULT_REGION="$REGION"
export AWS_REGION="$REGION"

mkdir -p "$STATE_DIR"
cd "$TF_DIR"

echo "==> terraform init/apply (ECR + IAM + VPC + EKS ~15–25 min)…"
terraform init -input=false
terraform apply -input=false -auto-approve \
  -var="aws_region=${REGION}" \
  -state="${STATE_DIR}/terraform.tfstate"

AK=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw katana_access_key_id)
SK=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw katana_secret_access_key)
REPO=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw ecr_repository_url)
NAME=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw ecr_repository_name)
ACCT=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw aws_account_id)
CLUSTER=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw eks_cluster_name)
IRSA=$(terraform output -state="${STATE_DIR}/terraform.tfstate" -raw katana_irsa_role_arn)

umask 077
cat >"$GOOD" <<EOF
# Generated by deploy/e2e-aws/apply.sh — DO NOT COMMIT
# Destroy with: bash deploy/e2e-aws/destroy.sh
export AWS_ACCESS_KEY_ID=${AK}
export AWS_SECRET_ACCESS_KEY=${SK}
export AWS_REGION=${REGION}
export AWS_DEFAULT_REGION=${REGION}
export KATANA_E2E_ECR_REPOSITORY_URL=${REPO}
export KATANA_E2E_ECR_REPOSITORY_NAME=${NAME}
export KATANA_E2E_AWS_ACCOUNT_ID=${ACCT}
export KATANA_E2E_EKS_CLUSTER=${CLUSTER}
export KATANA_E2E_IRSA_ROLE_ARN=${IRSA}
EOF
cp -a "$GOOD" "$GOOD_ROOT"

echo
echo "Wrote scanner credentials → ${GOOD}"
echo "ECR repo: ${REPO}"
echo "EKS cluster: ${CLUSTER}"
echo "Next: bash deploy/e2e-aws/deploy-katana.sh"
echo "Tear down: bash deploy/e2e-aws/destroy.sh"
